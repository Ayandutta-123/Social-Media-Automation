export type EventCategory = 'tech' | 'festival' | 'national' | 'observance';

export interface FestivalDef {
  id: string;
  name: string;
  region: CalendarRegion;
  category: EventCategory;
  month: number;
  day: number;
  year?: number;
  description: string;
  hashtagHints: string[];
  promptHints: string;
}

function ev(
  id: string,
  name: string,
  region: CalendarRegion,
  category: EventCategory,
  month: number,
  day: number,
  description: string,
  tags: string[],
  prompt: string,
  year?: number,
): FestivalDef {
  return {
    id,
    name,
    region,
    category,
    month,
    day,
    year,
    description,
    hashtagHints: tags,
    promptHints: prompt,
  };
}

