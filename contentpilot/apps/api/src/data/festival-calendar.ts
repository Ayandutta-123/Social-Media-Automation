function pad(n: number) {
  return String(n).padStart(2, '0');
}

/** `eu-easter-2026` → `eu-easter` so old generate ids still resolve. */
export function canonicalFestivalId(id: string): string {
  return id.replace(/-20\d{2}$/, '');
}

function isSupersededFixed(f: FestivalDef): boolean {
  if (RECURRING_IDS.has(f.id)) return true;
  const canon = canonicalFestivalId(f.id);
  if (canon !== f.id && RECURRING_IDS.has(canon)) return true;
  return f.id.startsWith('tech-programmer-');
}

function wantsRegion(region: CalendarRegion, regions: Set<CalendarRegion> | null): boolean {
  if (!regions) return true;
  if (region === 'global') {
    return regions.has('global') || [...regions].some((r) => r !== 'global');
  }
  return regions.has(region);
}

function parseYmd(date: string): { year: number; month: number; day: number } | null {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(date);
  if (!m) return null;
  return { year: Number(m[1]), month: Number(m[2]), day: Number(m[3]) };
}

function fromRecurring(
  r: (typeof RECURRING)[number],
  date: string,
  source: CalendarEvent['source'],
): CalendarEvent | null {
  const parts = parseYmd(date);
  if (!parts) return null;
  return {
    id: r.id,
    name: r.name,
    region: r.region,
    category: r.category,
    month: parts.month,
    day: parts.day,
    description: r.description,
    hashtagHints: r.hashtagHints,
    promptHints: r.promptHints,
    date,
    source,
  };
}

export function listFestivalEvents(opts: {
  year: number;
  month?: number;
  regions?: CalendarRegion[];
  categories?: EventCategory[];
  overrides?: CatalogDateOverride[];
}): CalendarEvent[] {
  const regions = opts.regions?.length ? new Set(opts.regions) : null;
  const categories = opts.categories?.length ? new Set(opts.categories) : null;
  const out: CalendarEvent[] = [];
  const seen = new Set<string>();
  const overrideByKey = new Map<string, CatalogDateOverride>();
  const extras: CatalogDateOverride[] = [];
  for (const row of opts.overrides || []) {
    if (row.source === 'external' || row.eventKey.startsWith('ext-')) extras.push(row);
    else overrideByKey.set(row.eventKey, row);
  }

  for (const r of RECURRING) {
    const db = overrideByKey.get(r.id);
    const date = db?.date || OVERRIDES[r.id]?.[opts.year] || resolveRuleDate(r.when, opts.year);
    if (!date) continue;
    const ev = fromRecurring(r, date, db ? 'override' : OVERRIDES[r.id]?.[opts.year] ? 'override' : 'rule');
    if (!ev || ev.date.slice(0, 4) !== String(opts.year)) continue;
    if (opts.month != null && ev.month !== opts.month) continue;
    if (categories && !categories.has(ev.category)) continue;
    if (!wantsRegion(ev.region, regions)) continue;
    seen.add(r.id);
    out.push(ev);
  }

  for (const f of FIXED) {
    if (isSupersededFixed(f)) continue;
    if (f.year != null && f.year !== opts.year) continue;
    if (opts.month != null && f.month !== opts.month) continue;
    if (categories && !categories.has(f.category)) continue;
    if (!wantsRegion(f.region, regions)) continue;
    const key = canonicalFestivalId(f.id);
    if (seen.has(key) || seen.has(f.id)) continue;
    seen.add(f.id);
    out.push({
      ...f,
      date: `${opts.year}-${pad(f.month)}-${pad(f.day)}`,
      source: 'rule',
    });
  }

  for (const row of extras) {
    const parts = parseYmd(row.date);
    if (!parts || parts.year !== opts.year) continue;
    if (opts.month != null && parts.month !== opts.month) continue;
    const region = (row.region || 'global') as CalendarRegion;
    const category = (row.category || 'observance') as EventCategory;
    if (categories && !categories.has(category)) continue;
    if (!wantsRegion(region, regions)) continue;
    if (seen.has(row.eventKey)) continue;
    seen.add(row.eventKey);
    out.push({
      id: row.eventKey,
      name: row.name || row.eventKey,
      region,
      category,
      month: parts.month,
      day: parts.day,
      description: row.description || '',
      hashtagHints: row.hashtagHints || [],
      promptHints: row.promptHints || '',
      date: row.date,
      source: 'external',
    });
  }

  return out.sort((a, b) => a.date.localeCompare(b.date) || a.name.localeCompare(b.name));
}

export function getFestivalById(id: string, year?: number): CalendarEvent | null {
  const y = year ?? new Date().getFullYear();
  const canon = canonicalFestivalId(id);
  const recurring = RECURRING.find((r) => r.id === id || r.id === canon);
  if (recurring) {
    const date = OVERRIDES[recurring.id]?.[y] || resolveRuleDate(recurring.when, y);
    return date ? fromRecurring(recurring, date, OVERRIDES[recurring.id]?.[y] ? 'override' : 'rule') : null;
  }
  const def =
    FIXED.find((f) => f.id === id && !isSupersededFixed(f)) ||
    FIXED.find((f) => canonicalFestivalId(f.id) === canon && !isSupersededFixed(f) && (f.year == null || f.year === y));
  if (!def) return null;
  return {
    ...def,
    date: `${y}-${pad(def.month)}-${pad(def.day)}`,
    source: 'rule',
  };
}

/** Baseline catalog size (fixed + recurring rules). Year-pinned dupes are not counted. */
export function countCatalogEntries() {
  const fixedKept = FIXED.filter((f) => !isSupersededFixed(f) && f.year == null).length;
  return fixedKept + RECURRING.length;
}

export function catalogYearStats(year: number) {
  const events = listFestivalEvents({ year });
  return {
    year,
    count: events.length,
    recurring: RECURRING.length,
    baseline: countCatalogEntries(),
  };
}
